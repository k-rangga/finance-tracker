// Run: node scripts/gen-schema.mjs > supabase/schema.sql
// The Supabase tables, generated from the Sheet's own table list (apps-script/Sheets.js TABLES / NUMERIC), so the
// two never drift apart. Every table gets `user_id`, a primary key of (user_id, its first column), and row-level
// security: a signed-in user only ever sees and changes their own rows.
import fs from 'node:fs';
import vm from 'node:vm';

const dir = new URL('../apps-script/', import.meta.url).pathname;
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(dir + 'Sheets.js', 'utf8') + '\n;this.TABLES = TABLES; this.NUMERIC = NUMERIC;', ctx);
const { TABLES, NUMERIC } = ctx;

const q = s => '"' + s + '"';
const out = [
  '-- Generated by scripts/gen-schema.mjs from apps-script/Sheets.js. Run it once in Supabase → SQL Editor.',
  '-- Safe to run again: it only adds what is missing.',
  '',
];

for (const [name, cols] of Object.entries(TABLES)) {
  const nums = NUMERIC[name] || [];
  out.push(`create table if not exists public.${q(name)} (`);
  out.push('  user_id uuid not null references auth.users (id) on delete cascade,');
  for (const c of cols) out.push(`  ${q(c)} ${nums.includes(c) ? 'double precision' : 'text'}${c === cols[0] ? ' not null' : ''},`);
  // Row order, as rows were added (the Sheet's order); an update keeps a row's place.
  out.push('  seq bigint generated by default as identity,');
  out.push(`  primary key (user_id, ${q(cols[0])})`);
  out.push(');');
  // Columns added to the Sheet later are added here too.
  for (const c of cols) out.push(`alter table public.${q(name)} add column if not exists ${q(c)} ${nums.includes(c) ? 'double precision' : 'text'};`);
  out.push(`create index if not exists ${name}_user_seq on public.${q(name)} (user_id, seq);`);
  out.push(`alter table public.${q(name)} enable row level security;`);
  out.push(`drop policy if exists "own rows" on public.${q(name)};`);
  out.push(`create policy "own rows" on public.${q(name)} for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());`);
  out.push('');
}

out.push(
  '-- Small settings and state (what Apps Script kept in Script properties): settings, prices, gmail, flags.',
  'create table if not exists public.props (',
  '  user_id uuid not null references auth.users (id) on delete cascade,',
  '  key text not null,',
  '  value text,',
  '  primary key (user_id, key)',
  ');',
  'alter table public.props enable row level security;',
  'drop policy if exists "own rows" on public.props;',
  'create policy "own rows" on public.props for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());',
  '',
  '-- Each user\'s Google connection (Gmail and Drive). Only the server reads it: no policy, so signed-in users',
  '-- can\'t read their refresh token from the browser.',
  'create table if not exists public.google_tokens (',
  '  user_id uuid primary key references auth.users (id) on delete cascade,',
  '  email text,',
  '  refresh_token text not null,',
  '  scope text,',
  '  updated_at timestamptz not null default now()',
  ');',
  'alter table public.google_tokens enable row level security;',
  '',
  '-- Hourly sync: Supabase calls the app every hour (Gmail import at the usual hours, Hyperliquid every 6 hours).',
  '-- Turn on the pg_cron and pg_net extensions (Database → Extensions), put your app URL and CRON_SECRET in the',
  '-- two lines below, and run this part once.',
  '-- select cron.schedule(',
  "--   'hourly-sync', '5 * * * *',",
  "--   $$ select net.http_post(url := 'https://YOUR-APP.vercel.app/api/cron', headers := jsonb_build_object('Authorization', 'Bearer YOUR_CRON_SECRET'), timeout_milliseconds := 300000) $$",
  '-- );',
);

console.log(out.join('\n'));
